"""Build bundled Google translations; never runs on the user's phone.

Set BLIND_WAY_GCP_ACCOUNT to choose an account without changing active CLI state.
Only product strings are sent; no user addresses, keys, audio or camera frames.
"""
import concurrent.futures, html, json, os, pathlib, re, subprocess, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROJECT = 'project-8eeef9d3-080a-4f49-95e'
account_args = ['--account='+os.environ['BLIND_WAY_GCP_ACCOUNT']] if os.environ.get('BLIND_WAY_GCP_ACCOUNT') else []
token = subprocess.run(['gcloud.cmd', 'auth', 'print-access-token', *account_args],
                       check=True, capture_output=True, text=True).stdout.strip()
locale_source = (ROOT/'lib/src/config/languages.dart').read_text(encoding='utf-8')
locales = re.findall(r"    '([a-z]{2}-[A-Z]{2})':", locale_source)
sources = set()
for filename in ['lib/src/services/walking_navigation.dart', 'lib/src/ui/navigation_screen.dart', 'backend/src/navigation.ts']:
    content = (ROOT/filename).read_text(encoding='utf-8')
    for text in re.findall(r"'([^'\n]*)'", content):
        if re.match(r'[A-Z{]', text) and ' ' in text and '$' not in text:
            sources.add(text)
sources = sorted(sources)
catalog = {'en-IN':dict(zip(sources,sources)), 'en-US':dict(zip(sources,sources))}
cache = ROOT/'infra/navigation-translations.json'
existing = json.loads(cache.read_text(encoding='utf-8')) if cache.exists() else {}
def translate(locale):
    if locale in catalog:return locale,catalog[locale]
    if locale in existing and set(existing[locale]) == set(sources): return locale,existing[locale]
    language = {'od':'or'}.get(locale[:2],locale[:2])
    contents = [re.sub(r'(\{\w+\})',r'<span class="notranslate">\1</span>',html.escape(s)) for s in sources]
    body = json.dumps({'contents':contents,'sourceLanguageCode':'en','targetLanguageCode':language,'mimeType':'text/html'}).encode()
    request = urllib.request.Request('https://translation.googleapis.com/v3/projects/'+PROJECT+':translateText',data=body,
        headers={'Authorization':'Bearer '+token,'Content-Type':'application/json','x-goog-user-project':PROJECT})
    with urllib.request.urlopen(request,timeout=60) as response:data=json.load(response)
    translated = [html.unescape(re.sub(r'<[^>]+>','',t['translatedText'])) for t in data['translations']]
    assert len(translated)==len(sources)
    for source,target in zip(sources,translated):
        assert sorted(re.findall(r'\{\w+\}',source))==sorted(re.findall(r'\{\w+\}',target)),(locale,source,target)
        assert target.strip(),locale
    return locale,dict(zip(sources,translated))
with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
    for locale,strings in pool.map(translate,locales):
        catalog[locale]=strings
        print(locale,len(strings),flush=True)
cache.write_text(json.dumps(catalog,ensure_ascii=False,indent=2),encoding='utf-8')
payload=json.dumps(catalog,ensure_ascii=False,indent=2).replace('$',r'\$')
(ROOT/'lib/src/config/navigation_translations.dart').write_text(
    '// Generated by infra/generate-navigation-translations.py. Google Cloud Translation.\n'
    'const navigationTranslations = <String, Map<String, String>>'+payload+';\n',encoding='utf-8')
